// Runs before the production build on Vercel: writes the backend's address (the API_URL
// environment variable set in Vercel's project settings) into environment.prod.ts,
// so the address can change without editing code.
import { writeFileSync } from 'node:fs';

const apiUrl = (process.env.API_URL ?? '').trim().replace(/\/+$/, '');

if (!apiUrl) {
  console.error('API_URL is not set. Add it in Vercel: Project Settings -> Environment Variables (see DEPLOY.md).');
  process.exit(1);
}
if (!apiUrl.startsWith('https://')) {
  console.error(`API_URL must start with https:// (got "${apiUrl}").`);
  process.exit(1);
}

writeFileSync(
  new URL('../src/environments/environment.prod.ts', import.meta.url),
  `// Generated by scripts/set-api-url.mjs during the Vercel build.\nexport const environment = {\n  apiUrl: '${apiUrl}'\n};\n`
);
console.log(`API URL set to ${apiUrl}`);
